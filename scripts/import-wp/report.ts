import type { Item } from '../../src/content/schema.ts';

// Builds docs/migration-report.md: what was imported, what was changed on the
// way, and what was left behind.

export interface ImportReport {
  sourceFile: string;
  items: Item[];
  itemNotes: Map<string, string[]>;
  spellingNotes: string[];
  gridNotes: string[];
  categories: number;
  tags: number;
  redirects: number;
  skippedRedirects: string[];
  copiedFiles: number;
  copiedBytes: number;
  missingFiles: string[];
  /** Post counts by type/status that were not imported, e.g. "post / publish" -> 22. */
  skippedPosts: Map<string, number>;
  /** Attachments of imported items that no gallery or cover uses. */
  unusedItemAttachments: string[];
  /** Attachments not linked to any imported item. */
  otherAttachments: number;
  resumeNotes: string[];
  samples: { slug: string; before: string; after: Item }[];
}

// Theme and plugin settings that have no equivalent in the new site.
const UNMAPPED_FIELDS = [
  ['Space between images (`tiny` / `small`)', 'one site-wide spacing in the new styles'],
  [
    'Overlay skin, parallax, header/footer/title-area toggles',
    'theme display options; the new design is fixed',
  ],
  [
    'Subtitle meta (`edge_title_area_subtitle_meta`)',
    'same text as the `<h4>` in the body, which is used',
  ],
  [
    '"Back to" link (`portfolio_single_back_to_link`)',
    'item pages link back to the portfolio grid',
  ],
  ['`_upt_*` (Ultimate Post Thumbnails), `_cdp_*` (post duplicator)', 'plugin bookkeeping'],
  ['`edge_portfolios` custom fields', 'one item had a leftover "Test" field'],
  ['Attachment titles, captions, alt text', 'none were filled in; starter alt text was generated'],
];

export function renderReport(report: ImportReport): string {
  const { items } = report;
  const images = items.reduce(
    (sum, item) => sum + item.media.filter((m) => m.type === 'image').length,
    0,
  );
  const videos = items.reduce(
    (sum, item) => sum + item.media.filter((m) => m.type === 'youtube').length,
    0,
  );
  const lines: string[] = [];
  const add = (...text: string[]) => lines.push(...text);

  add(
    '# Migration report',
    '',
    'Generated by `npm run import:wp` from the WordPress export. Re-running the import',
    'regenerates this file.',
    '',
    '## Summary',
    '',
    '| | |',
    '|---|---|',
    `| Source | \`_source/${report.sourceFile}\` + \`legacy/wp-export/\` |`,
    `| Portfolio items | ${items.length} |`,
    `| Gallery images | ${images} |`,
    `| YouTube videos | ${videos} |`,
    `| Files copied to \`src/content/media/\` | ${report.copiedFiles} (${(report.copiedBytes / 1024 / 1024).toFixed(1)} MB) |`,
    `| Categories / tags | ${report.categories} / ${report.tags} |`,
    `| Old-URL redirects | ${report.redirects} |`,
    `| Missing files | ${report.missingFiles.length || 'none'} |`,
    '',
    '## Items',
    '',
    'In front-page order.',
    '',
    '| Item | Layout | Images | Videos | Categories | Tags |',
    '|---|---|---|---|---|---|',
    ...items.map((item) => {
      const layout =
        item.layout.type === 'stacked'
          ? 'stacked'
          : `${item.layout.type}, ${item.layout.columns} cols`;
      const count = (type: string) => item.media.filter((m) => m.type === type).length;
      return `| ${item.title} (\`${item.slug}\`) | ${layout} | ${count('image')} | ${count('youtube') || ''} | ${item.categories.join(', ')} | ${item.tags.join(', ')} |`;
    }),
    '',
    '## Changes made during the import',
    '',
    'Check these. Each can be edited in the item files (or the admin, later).',
    '',
  );

  const itemsWithNotes = items.filter((item) => report.itemNotes.get(item.slug)?.length);
  if (itemsWithNotes.length) {
    add('### Per item', '');
    for (const item of itemsWithNotes) {
      add(`- **${item.slug}**`);
      for (const note of report.itemNotes.get(item.slug) ?? []) add(`  - ${note}`);
    }
    add('');
  }
  add(
    '### Spelling made consistent across items',
    '',
    ...(report.spellingNotes.length ? report.spellingNotes.map((note) => `- ${note}`) : ['- none']),
    '',
    '### Front-page grid',
    '',
    "- Order taken from the old home page (WordPress `menu_order` values tie, so they can't be used).",
    '- Grid settings: 5 / 3 / 2 / 1 tiles per row (wide / desktop / tablet / phone), 10px gap, as in the theme.',
    '- All items start with `featured: false`, matching the old grid.',
    ...report.gridNotes.map((note) => `- ${note}`),
    '',
    '### Every item',
    '',
    '- Alt text is generated as "<title> – view N" (WordPress had none). Worth rewriting with real descriptions.',
    "- Image files are renamed to lowercase, and WordPress's `-scaled` suffix is dropped.",
    '- Visual Composer shortcodes and leftover browser-extension markup (`gtx-trans`) are removed.',
    '',
    '## Resume',
    '',
    ...report.resumeNotes.map((note) => `- ${note}`),
    '',
    '## Not imported',
    '',
    '### Posts',
    '',
    '| Type / status | Count | Why |',
    '|---|---|---|',
    ...[...report.skippedPosts].map(
      ([kind, count]) => `| ${kind} | ${count} | ${skipReason(kind)} |`,
    ),
    '',
    '### Images',
    '',
    `- ${report.unusedItemAttachments.length} images attached to imported items aren't used in any gallery or as a cover (older versions, replaced shots). They stay on the live site until it shuts down:`,
    ...report.unusedItemAttachments.map((file) => `  - \`${file}\``),
    `- ${report.otherAttachments} other uploads belong to theme demo content or nothing at all.`,
    ...(report.missingFiles.length
      ? ['', '### Missing files', '', ...report.missingFiles.map((file) => `- \`${file}\``)]
      : []),
    '',
    '### Old URLs',
    '',
    `${report.redirects} old item URLs forward to their current item (\`src/content/redirects.json\`). Skipped:`,
    '',
    ...report.skippedRedirects.map((note) => `- ${note}`),
    '',
    '### Theme settings with no equivalent',
    '',
    '| Setting | Why it was dropped |',
    '|---|---|',
    ...UNMAPPED_FIELDS.map(([field, why]) => `| ${field} | ${why} |`),
    '',
    '## Before / after samples',
    '',
  );

  for (const sample of report.samples) {
    const { title, subtitle, description, software, client } = sample.after;
    add(
      `### ${sample.slug}`,
      '',
      'WordPress post body:',
      '',
      '```html',
      sample.before.trim(),
      '```',
      '',
      'Item file fields:',
      '',
      '```json',
      JSON.stringify({ title, subtitle, description, software, client }, null, 2),
      '```',
      '',
    );
  }
  return lines.join('\n');
}

function skipReason(kind: string): string {
  if (kind.startsWith('portfolio-item')) return 'unpublished theme demo items';
  if (kind.startsWith('post')) return '2017 theme demo blog posts';
  if (kind.startsWith('team-member') || kind.startsWith('testimonials'))
    return 'theme demo content';
  if (kind.startsWith('page'))
    return 'rebuilt as React pages (home, resume, contact) or demo drafts';
  if (kind.startsWith('nav_menu_item')) return 'menu is defined in code';
  if (kind.startsWith('custom_css')) return 'replaced by the new styles';
  if (kind.startsWith('attachment')) return 'only the files used by imported items are copied';
  return '';
}
